sys.path.insert(0, "/private/tmp/claude-501/-Users-skandar-skandar/5ac02630-dcb3-4273-9a54-1d410426553c/scratchpad")
from maksi_style import *
from reportlab.platypus import PageBreak, NextPageTemplate, Spacer
from reportlab.lib.units import mm

rows=json.load(open("/tmp/open/rating.json"))
lots=json.load(open("/tmp/wp/analysis.json"))
PR=json.load(open("/private/tmp/claude-501/-Users-skandar-skandar/5ac02630-dcb3-4273-9a54-1d410426553c/scratchpad/prices.json"))
oi=[r for r in rows if "одного источника" in r["method"]]
bad=[r for r in oi if r["m1"] is not None and r["m1"]<=0]

story=[NextPageTemplate("body"),PageBreak()]

story+=[P("зачем этот обзор","kick"),P("Как устроен рынок ниши","h1")]
story+=[P("Обзор отвечает на вопрос «стоит ли вообще заходить в эту нишу»: сколько там закупок, "
          "какая конкуренция, с какими скидками выигрывают и почему часть закупок регулярно "
          "проваливается. Разбор конкретных лотов — во втором отчёте.","lead")]
story+=[panel(["По слову «кондиционер» открыто 35 лотов.",
               "33 из них — «из одного источника по несостоявшимся закупкам»: поставщик уже "
               "приглашён, участвовать нельзя.",
               "Реально доступны 2 лота — запрос ценовых предложений и аукцион."],accent_first=True)]

story+=[Spacer(1,5*mm),P("Способы закупки среди открытых лотов","h2")]
story+=[table(["Способ закупки","Лотов","Можно ли участвовать"],
  [["Из одного источника по несостоявшимся","33","нет — поставщик приглашён"],
   ["Запрос ценовых предложений","1","да"],
   ["Аукцион","1","да"]],[84*mm,20*mm,52*mm],["L","R","L"])]
story+=[Spacer(1,2*mm),P("Фильтр по способу закупки — первое, что должен делать агент. Без него "
                         "рейтинг наполняется лотами, в которые нельзя зайти.","small")]

story+=[PageBreak(),P("почему закупки проваливаются","kick"),P("Цена заказчика ниже рынка","h1")]
story+=[P("Мы посчитали отсеянные лоты по рыночным ценам — и стало видно, почему они "
          "не состоялись: заказчик закладывает сумму, за которую товар просто не купить.","body")]
data=[[r["lot"],trim(r["char"],36),money(r["plan"]),money(r["cost"]),"−"+money(abs(r["m1"]))]
      for r in sorted(bad,key=lambda r:r["m1"])[:10]]
story+=[table(["Лот","Что просят","Плановая","Рынок","Разрыв"],data,
              [28*mm,56*mm,24*mm,24*mm,28*mm],["L","L","R","R","R"],cols={4:"cellLoss"})]
story+=[Spacer(1,3*mm),
  P("Самый показательный пример: кассетный кондиционер на 70–75 м² просят за 125 000 ₸, "
    "тогда как минимальная рыночная цена такого класса — 531 900 ₸. Разрыв в четыре раза.","body")]
story+=[P("<b>Практический вывод для входа в нишу:</b> если по позиции закупки регулярно "
          "не состаиваются, дело почти всегда в нереальной цене, а не в отсутствии поставщиков. "
          "Такие лоты видно сразу, и тратить на них время не нужно.","body")]

story+=[PageBreak(),P("цены","kick"),P("Сколько стоит товар на рынке","h1")]
story+=[P("Цены сняты с двух площадок в один день. Минимум нужен для расчёта маржи, среднее "
          "показывает, насколько нижняя цена случайна.","body")]
story+=[P("Kaspi","h3")]
story+=[table(["Тип","Позиций","Минимум","Среднее","Максимум"],
  [[n,str(len(a)),money(min(a)),money(statistics.mean(a)),money(max(a))] for n,a in PR["kaspi"].items()],
  [64*mm,16*mm,25*mm,25*mm,26*mm])]
story+=[P("Satu","h3")]
story+=[table(["Тип","Позиций","Минимум","Среднее","Максимум"],
  [[n,str(len(a)),money(min(a)),money(statistics.mean(a)),money(max(a))] for n,a in PR["satu"].items()],
  [64*mm,16*mm,25*mm,25*mm,26*mm])]
story+=[Spacer(1,3*mm),
  P("<b>Ни одна площадка не дешевле всегда.</b> По «семёрке» Satu даёт 89 388 ₸, по «девятке» "
    "выгоднее Kaspi — 99 999 ₸ против 136 000 ₸. Правило: брать минимум из обеих.","body")]
story+=[P("Обе площадки розничные, то есть это <b>потолок</b> закупочной цены. Ozon для "
          "казахстанских тендеров не подходит — там та же «девятка» стоит от 200 000 ₸, "
          "дороже, чем платит заказчик.","small")]

story+=[PageBreak(),P("конкуренты","kick"),P("Кто работает в нише","h1")]
wins=collections.Counter(l["winner"] for l in lots)
part=collections.Counter()
for l in lots:
    for nm,_ in l["all"]: part[nm]+=1
GEN="товарищество с ограниченн"
rw=[]
for w,c in wins.most_common(14):
    if GEN in w.lower(): continue
    sub=[l["disc"] for l in lots if l["winner"]==w]
    pt=max(part.get(w,0),c)
    rw.append([w,str(pt),str(c),f"{c/pt*100:.0f}%",f"{statistics.mean(sub):.1f}%"])
    if len(rw)>=8: break
story+=[table(["Поставщик","Участий","Побед","Конверсия","Средняя скидка"],rw,
              [56*mm,20*mm,18*mm,22*mm,40*mm])]
story+=[Spacer(1,3*mm),
  P("<b>Техснабжение доминирует:</b> участвует в 29 закупках из 50 и выигрывает 13 — почти "
    "каждый второй заход. Средняя скидка у него 14,3%, то есть режет цену глубже рыночной "
    "медианы. Это главный конкурент в нише.","body")]
story+=[P("Остальные участвуют редко и выигрывают со скидкой 0–10%. Там, где Техснабжения нет, "
          "торг заметно мягче.","body")]
story+=[P("В таблицу не включены компании, чьё название в протоколе обрезано до «Товарищество "
          "с ограниченной ответственностью» — различить их по протоколу нельзя.","small")]

story+=[PageBreak(),P("конкуренция","kick"),P("Сколько участников в лоте","h1")]
dist=collections.Counter(l["n"] for l in lots); tot=len(lots)
story+=[table(["Сколько подавалось","Лотов","Доля"],
  [[f"{k} участник{'' if k==1 else 'а' if k<5 else 'ов'}",str(v),f"{v/tot*100:.0f}%"]
   for k,v in sorted(dist.items())],[70*mm,25*mm,61*mm],["L","R","R"])]
story+=[Spacer(1,3*mm),
  P("Медиана — <b>2 участника</b>, среднее 2,8, максимум 8. В <b>7 закупках из 50 участник был "
    "единственным</b> — там скидка не нужна вовсе. В сумме в 60% закупок конкурентов ноль "
    "или один. Ниша малоконкурентная.","body")]

story+=[Spacer(1,6*mm),P("прошлые цены","kick"),P("С какой скидкой выигрывают","h2")]
ds=[l["disc"] for l in lots]
story+=[table(["Показатель","Значение"],
  [["Скидка победителя от плановой цены","медиана 10,0% · среднее 12,0%"],
   ["Половина закупок укладывается в","3,8 – 16,8%"],
   ["Крайние значения","0% и 45,4%"],
   ["Отрыв победителя от второго места","медиана 3,85% · среднее 6,45%"]],
  [86*mm,70*mm],["L","R"])]
story+=[Spacer(1,3*mm),
  P("<b>Медиана скидки — ровно 10%, то есть точно порог демпинга.</b> Рынок стоит на границе, "
    "за которой нужно вносить обеспечение и замораживать деньги. Выигрывают с отрывом 3–4% — "
    "резать цену глубже смысла нет.","body")]

story+=[PageBreak(),P("примеры","kick"),P("Как это выглядит в протоколах","h1")]
ex=sorted(lots,key=lambda l:-l["n"])[:12]
story+=[table(["Лот","Уч.","Плановая","Победа","Скидка","Победитель"],
  [[l["lot"],str(l["n"]),money(l["plan"]),money(l["win"]),f"{l['disc']}%",trim(l["winner"],22)]
   for l in ex],[30*mm,11*mm,24*mm,24*mm,17*mm,50*mm],["L","R","R","R","R","L"])]
story+=[Spacer(1,4*mm),P("Итог по нише","h2")]
story+=[panel(["Заходить стоит: конкурентов мало, каждая седьмая закупка идёт без борьбы.",
               "Но половина открытых лотов нереальна по цене — их надо отсеивать сразу.",
               "Главный конкурент один, и его поведение предсказуемо: он режет цену на 14%."])]

cover=make_cover("тендерный агент · обзор рынка","Кондиционеры","обзор ниши на 25 июля",
  ["Сколько закупок идёт, кто в них участвует, с какими",
   "скидками выигрывают и почему треть лотов регулярно",
   "проваливается, не найдя поставщика."],
  [("35","открытых лотов"),("2","доступны для участия"),("50","закупок разобрано")],
  "Госзакупки РК · прогон 25 июля 2026")
page=make_page("тендерный агент · обзор рынка","кондиционеры · 25.07.2026")
print(build("1-obzor-rynka.pdf",
            story,cover,page,"Обзор рынка — кондиционеры"))
